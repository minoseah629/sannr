function codeFrom(error, allowed, fallback) {
  try {
    const code = error?.code;
    return allowed.has(code) ? code : fallback;
  } catch { return fallback; }
}

export function publicProtocolCode(error, fallback) { return codeFrom(error, publicCodes, fallback); }

// Target/auth/policy producers use curated plain records. Preserve their
// remediation while ensuring even an injected target error cannot carry a
// foreign code or an accessor that changes after validation.
export function publicProtocolTargetError(error) {
  const refused = { code: 'PROTOCOL_INPUT_INVALID', message: 'The protocol target could not be prepared. Check its configuration.' };
  const code = codeFrom(error, targetCodes, null);
  if (code === null) return refused;
  try {
    const result = { code };
    for (const key of ['kind', 'message', 'next', 'details']) {
      const descriptor = Object.getOwnPropertyDescriptor(error, key);
      if (descriptor && Object.hasOwn(descriptor, 'value')) result[key] = descriptor.value;
    }
    if (typeof result.message !== 'string') result.message = refused.message;
    return result;
  } catch { return refused; }
}
